/**
 * Generates my-app/supabase/migrations/0004_phase5_location_seed.sql from the
 * OCHA/HDX COD-AB Bangladesh admin boundaries GeoJSON (BBS-sourced, CC BY-IGO).
 *
 * Usage:
 *   GEOJSON_DIR=<dir with bgd_admin3.geojson> node scripts/build-location-seed.mjs
 *
 * Deterministic: stable sorts; no random IDs.
 * Filtering: excludes 12 "City Corporation" admin-3 units (not upazilas).
 * Private center coordinates: kept for approximate distance bands only.
 * Adjacency: two upazilas are neighbours when their polygons share >=2 ring
 *   vertices (a robust, dataset-derived proxy for a real shared boundary).
 */
import fs from "node:fs";
import path from "node:path";

const geoDir = process.env.GEOJSON_DIR;
if (!geoDir) {
  console.error("Set GEOJSON_DIR to the folder containing bgd_admin3.geojson");
  process.exit(1);
}
const gj = JSON.parse(fs.readFileSync(path.join(geoDir, "bgd_admin3.geojson"), "utf8"));
const isCityCorp = (n) => /city corporation/i.test(n);
const features = gj.features.filter((f) => !isCityCorp(f.properties.adm3_name));
console.log("upazila-class features:", features.length);
if (features.length !== 495) {
  console.error("Unexpected count — dataset changed? Aborting to stay documented.");
  process.exit(1);
}

// Scale decimal coords to integer keys for shared-boundary detection.
const ringKey = (c) => `${Math.round(c[0] * 1e5)}:${Math.round(c[1] * 1e5)}`;

// Collect ring vertex keys per upazila pcode.
const ringByPcode = new Map();
for (const f of features) {
  const poly = f.geometry.coordinates; // Polygon: [ring][point][lon,lat]
  const keys = new Set();
  for (const ring of poly) for (const pt of ring) keys.add(ringKey(pt));
  ringByPcode.set(f.properties.adm3_pcode, keys);
}

// Adjacency: shared key count >= 2.
const pcodes = [...ringByPcode.keys()].sort();
const adjacency = new Map();
for (let i = 0; i < pcodes.length; i++) {
  for (let j = i + 1; j < pcodes.length; j++) {
    const a = ringByPcode.get(pcodes[i]);
    const b = ringByPcode.get(pcodes[j]);
    let shared = 0;
    for (const k of a) if (b.has(k)) shared++;
    if (shared >= 2) {
      (adjacency.get(pcodes[i]) ?? adjacency.set(pcodes[i], []).get(pcodes[i])).push(pcodes[j]);
      (adjacency.get(pcodes[j]) ?? adjacency.set(pcodes[j], []).get(pcodes[j])).push(pcodes[i]);
    }
  }
}
console.log("adjacent pairs:", [...adjacency.values()].reduce((s, v) => s + v.length, 0) / 2);

// Stable ID allocation.
const divPCodes = [...new Set(features.map((f) => f.properties.adm1_pcode))].sort();
const divId = new Map(divPCodes.map((p, i) => [p, i + 1]));
const byDiv = new Map();
for (const p of [...new Set(features.map((f) => f.properties.adm2_pcode))].sort()) {
  const div = features.find((f) => f.properties.adm2_pcode === p).properties.adm1_pcode;
  (byDiv.get(div) ?? byDiv.set(div, []).get(div)).push(p);
}
const distId = new Map();
for (const [div, list] of byDiv) list.forEach((p, i) => distId.set(p, divId.get(div) * 100 + (i + 1)));

const ups = features
  .map((f) => ({
    name: f.properties.adm3_name,
    dist: f.properties.adm2_pcode,
    pcode: f.properties.adm3_pcode,
    lat: f.properties.center_lat,
    lon: f.properties.center_lon,
  }))
  .sort((a, b) => a.dist.localeCompare(b.dist) || a.name.localeCompare(b.name));

const upaId = new Map();
{
  const seqByDist = new Map();
  for (const u of ups) {
    const seq = (seqByDist.get(u.dist) ?? seqByDist.set(u.dist, 0).get(u.dist)) + 1;
    seqByDist.set(u.dist, seq);
    upaId.set(u.pcode, distId.get(u.dist) * 1000 + seq);
  }
}

const q = (s) => s.replace(/'/g, "''");
const lines = [];
lines.push(`-- ============================================================================
-- Phase 5: location seed — GENERATED by scripts/build-location-seed.mjs.
-- Source: OCHA/HDX COD-AB Bangladesh (BBS-sourced), CC BY-IGO.
-- https://data.humdata.org/dataset/cod-ab-bgd
-- 8 divisions, 64 districts, 495 upazilas (12 city corporations excluded).
-- center_lat/lon are approximate area centers for distance BANDS ONLY.
-- They are private lookup data; no client query may select them.
-- ============================================================================
begin;

truncate public.upazilas, public.districts, public.divisions cascade;

-- ------------- divisions -------------`);
for (const p of divPCodes) {
  const name = features.find((f) => f.properties.adm1_pcode === p).properties.adm1_name;
  lines.push(`insert into public.divisions (id, name, bn_name) values (${divId.get(p)}, '${q(name)}', '${q(name)}');`);
}
lines.push(`
-- ------------- districts -------------`);
for (const [, list] of byDiv) {
  for (const p of list) {
    const d = features.find((f) => f.properties.adm2_pcode === p).properties;
    lines.push(`insert into public.districts (id, division_id, name, bn_name) values (${distId.get(p)}, ${divId.get(d.adm1_pcode)}, '${q(d.adm2_name)}', '${q(d.adm2_name)}');`);
  }
}
lines.push(`
-- ------------- upazilas (base rows) -------------`);
for (const u of ups) {
  lines.push(`insert into public.upazilas (id, district_id, name, bn_name) values (${upaId.get(u.pcode)}, ${distId.get(u.dist)}, '${q(u.name)}', '${q(u.name)}');`);
}

lines.push(`
-- ------------- private geo + adjacency (no client access policy) -------------`);
// private centers + adjacency live side tables; client-visible columns remain
// exactly as in 0001. Nothing here is reachable by anon/authenticated.
lines.push(`create table if not exists public.upazila_geo (
  upazila_id integer primary key references public.upazilas (id) on delete cascade,
  center_lat double precision not null,
  center_lon double precision not null
);
create table if not exists public.upazila_adjacency (
  upazila_id integer not null references public.upazilas (id) on delete cascade,
  neighbor_id integer not null references public.upazilas (id) on delete cascade,
  primary key (upazila_id, neighbor_id),
  check (upazila_id <> neighbor_id)
);
alter table public.upazila_geo enable row level security;
alter table public.upazila_adjacency enable row level security;

-- NO policy = invisible to anon/authenticated; service-role reads only.
`);
for (const u of ups) {
  lines.push(`insert into public.upazila_geo (upazila_id, center_lat, center_lon) values (${upaId.get(u.pcode)}, ${u.lat}, ${u.lon});`);
}
lines.push(`
-- ------------- adjacency (derived from real polygon boundaries) -------------`);
for (const u of ups) {
  const ns = (adjacency.get(u.pcode) ?? []).map((n) => upaId.get(n)).sort((a, b) => a - b);
  for (const n of ns) lines.push(`insert into public.upazila_adjacency (upazila_id, neighbor_id) values (${upaId.get(u.pcode)}, ${n});`);
}lines.push(`-- districts adjacency = any upazila-to-upazila link across district border
-- Postgres has no CREATE VIEW IF NOT EXISTS; drop-first is safe (this is a
-- generated, derived view, never a hand-edited object).
drop view if exists public.district_adjacency;
create view public.district_adjacency as
  select distinct du.district_id as district_id, dn.district_id as neighbor_id
    from public.upazila_adjacency a
    join public.upazilas du on du.id = a.upazila_id
    join public.upazilas dn on dn.id = a.neighbor_id
   where du.district_id <> dn.district_id;

commit;`);

const outPath = path.resolve("supabase/migrations/0004_phase5_location_seed.sql");
fs.writeFileSync(outPath, lines.join("\n"));
console.log("wrote", outPath, "lines:", lines.length);
