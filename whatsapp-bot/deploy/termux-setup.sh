#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# RoktoSathi WhatsApp bridge — run it on an Android phone with Termux.
#
#   FREE, no credit card, no server to rent. The phone becomes the always-on
#   machine that holds the WhatsApp session; a Cloudflare Quick Tunnel gives it
#   a public HTTPS URL the Vercel app can call.
#
# Run inside Termux, from the whatsapp-bot folder:
#
#   bash deploy/termux-setup.sh --token '<WHATSAPP_BOT_TOKEN>'
#
# Options:
#   --token <value>     Shared secret. MUST equal WHATSAPP_BOT_TOKEN in Vercel.
#                       Omit it to reuse the value already in .env.
#   --app-url <url>     Where donor replies are forwarded. Defaults to the
#                       production site.
#   --port <n>          Local port for the bridge (default 3001).
#   --no-tunnel         Skip the public tunnel (local testing only).
#
# Read deploy/README.md ("No credit card?") before you start.
# ---------------------------------------------------------------------------
set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PORT=3001
TOKEN=""
APP_INBOUND_URL="https://blood-gamma-nine.vercel.app/api/whatsapp/inbound"
WITH_TUNNEL=1
DATA_DIR="$HOME/wwebjs-data"          # session lives OUTSIDE the checkout
LOG_DIR="$HOME/roktosathi-logs"

usage() {
  sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'
}

while [ $# -gt 0 ]; do
  case "$1" in
    --token)     TOKEN="${2:-}"; shift 2 ;;
    --app-url)   APP_INBOUND_URL="${2:-}"; shift 2 ;;
    --port)      PORT="${2:-}"; shift 2 ;;
    --no-tunnel) WITH_TUNNEL=0; shift ;;
    -h|--help)   usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage; exit 1 ;;
  esac
done

# --- 0. sanity ------------------------------------------------------------
if [ ! -d /data/data/com.termux ]; then
  echo "ERROR: this script is for Termux on Android." >&2
  echo "On a Linux server (VM/VPS) use: sudo bash deploy/setup-vm.sh --token '...'" >&2
  exit 1
fi
if [ ! -f "$REPO_DIR/bot.js" ]; then
  echo "ERROR: bot.js not found next to this script (looked in $REPO_DIR)." >&2
  exit 1
fi

step() { printf '\n\033[1m==> %s\033[0m\n' "$1"; }

# --- 1. packages ----------------------------------------------------------
step "Installing packages (Node, Chromium, cloudflared) — this takes a while"
pkg update -y
pkg install -y nodejs-lts git openssl termux-tools
# Chromium ships in the x11 repository, not the default one.
pkg install -y x11-repo
pkg update -y
pkg install -y chromium

NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
if [ "$NODE_MAJOR" -lt 18 ]; then
  echo "ERROR: whatsapp-web.js needs Node 18+, found $(node -v). Try: pkg install nodejs" >&2
  exit 1
fi

CHROME_BIN="$(command -v chromium-browser || command -v chromium || true)"
if [ -z "$CHROME_BIN" ] || [ ! -x "$CHROME_BIN" ]; then
  echo "ERROR: no chromium binary found after install." >&2
  echo "Try: pkg install x11-repo && pkg install chromium" >&2
  exit 1
fi
echo "node:     $(node -v)"
echo "chromium: $CHROME_BIN"

# Fail fast if the browser cannot actually launch on this device — the single
# most common Termux failure, and far cheaper to catch here than mid-pairing.
if ! "$CHROME_BIN" --headless --no-sandbox --disable-gpu --version >/dev/null 2>&1; then
  echo "WARNING: $CHROME_BIN --version failed. If pairing fails with 'Aw, Snap!'" >&2
  echo "         or a launch error, see the proot fallback in deploy/README.md." >&2
fi

# --- 2. keep Android from killing us -------------------------------------
step "Acquiring wake lock"
# termux-wake-lock ships in termux-tools (core). It stops Android from deep
# sleeping while the bridge is running.
termux-wake-lock || echo "wake lock failed — is another Termux session holding it?"
echo "Now also set: Settings → Apps → Termux → Battery → Unrestricted"

# --- 3. configuration -----------------------------------------------------
step "Writing $REPO_DIR/.env"
mkdir -p "$DATA_DIR" "$LOG_DIR"
ENV_FILE="$REPO_DIR/.env"

if [ -z "$TOKEN" ] && [ -f "$ENV_FILE" ]; then
  TOKEN="$(grep -E '^WHATSAPP_BOT_TOKEN=' "$ENV_FILE" | head -1 | cut -d= -f2- || true)"
fi
GENERATED=0
if [ -z "$TOKEN" ]; then
  TOKEN="$(openssl rand -hex 32)"
  GENERATED=1
fi

cat > "$ENV_FILE" <<EOF
# Generated by deploy/termux-setup.sh on $(date)
WHATSAPP_BOT_TOKEN=$TOKEN
BRIDGE_PORT=$PORT
APP_INBOUND_URL=$APP_INBOUND_URL
WWEBJS_DATA_PATH=$DATA_DIR
CHROME_PATH=$CHROME_BIN
# The phone opens http://localhost:$PORT/qr itself, so the public pairing page
# stays token-gated: never QR_PUBLIC=true on a tunnelled host.
QR_PUBLIC=false
EOF
chmod 600 "$ENV_FILE"
echo "config written (session dir: $DATA_DIR)"

if [ "$GENERATED" = "1" ]; then
  printf '\n\033[1;33mNEW TOKEN GENERATED — copy it into Vercel as WHATSAPP_BOT_TOKEN:\033[0m\n%s\n\n' "$TOKEN"
fi

# --- 4. dependencies ------------------------------------------------------
step "Installing npm packages (skipping the Chrome download — we have chromium)"
cd "$REPO_DIR"
# Puppeteer has no official Android build, so its postinstall download fails;
# PUPPETEER_SKIP_DOWNLOAD makes it use CHROME_PATH above instead.
if [ -f package-lock.json ]; then
  PUPPETEER_SKIP_DOWNLOAD=true npm ci --omit=dev
else
  PUPPETEER_SKIP_DOWNLOAD=true npm install --omit=dev
fi

# --- 5. auto-start after a reboot ----------------------------------------
step "Registering boot script (needs the Termux:Boot app to take effect)"
BOOT_DIR="$HOME/.termux/boot"
mkdir -p "$BOOT_DIR"
cat > "$BOOT_DIR/roktosathi.sh" <<EOF
#!/data/data/com.termux/files/usr/bin/sh
termux-wake-lock
cd "$REPO_DIR" && node bot.js >> "$LOG_DIR/bridge.log" 2>&1
EOF
chmod +x "$BOOT_DIR/roktosathi.sh"
echo "written: $BOOT_DIR/roktosathi.sh  (install Termux:Boot, open it once)"

# --- 6. public tunnel ----------------------------------------------------
PUBLIC_URL=""
if [ "$WITH_TUNNEL" = "1" ]; then
  step "Starting Cloudflare Quick Tunnel"
  pkg install -y cloudflared
  nohup cloudflared tunnel --url "http://localhost:$PORT" --no-autoupdate \
    > "$LOG_DIR/tunnel.log" 2>&1 &
  TUNNEL_PID=$!
  echo "$TUNNEL_PID" > "$LOG_DIR/tunnel.pid"
  for _ in $(seq 1 40); do
    PUBLIC_URL="$(grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' "$LOG_DIR/tunnel.log" 2>/dev/null | head -1 || true)"
    [ -n "$PUBLIC_URL" ] && break
    sleep 2
  done
  if [ -n "$PUBLIC_URL" ]; then
    printf '\n\033[1;32mPublic URL: %s\033[0m\n' "$PUBLIC_URL"
    echo "Tunnel PID: $TUNNEL_PID   (crashes? see $LOG_DIR/tunnel.log)"
  else
    echo "WARNING: no tunnel URL yet — check $LOG_DIR/tunnel.log" >&2
  fi
fi

# --- 7. run --------------------------------------------------------------
step "Starting the bridge (Ctrl+C stops it)"
cat <<EOF

  Pair the phone (one time):      http://localhost:$PORT/qr?token=$TOKEN
  Health check:                   curl $PUBLIC_URL/health

EOF
if [ -n "$PUBLIC_URL" ]; then
  cat <<EOF
  IMPORTANT — Quick Tunnel URLs are random and change on every restart.
  After each restart, update WHATSAPP_BOT_URL in Vercel to:
      $PUBLIC_URL
  and redeploy. (See deploy/README.md for the stable-URL options.)

EOF
fi
cat <<EOF
  Keep this Termux session alive: swipe down on the notification and tap
  "Acquire wakelock", and set Termux battery usage to Unrestricted.
  Logs: $LOG_DIR

EOF

# Supervise: if the bridge crashes, restart it instead of leaving donors
# silently un-alerted. The outbox in the app retries, but only while this is up.
while true; do
  echo "--- $(date) starting bridge ---"
  node bot.js || echo "--- bridge exited ($?), restarting in 5s ---"
  sleep 5
done
